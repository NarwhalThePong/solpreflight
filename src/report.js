'use strict';
const { rules } = require('./rules');
const { PRIORITY_ORDER } = require('./scan');

const byId = Object.fromEntries(rules.map(r => [r.id, r]));
const esc = s => String(s).replace(/\|/g, '\\|');

function toMarkdown(res) {
  const L = [];
  L.push('# Pre-audit self-review report', '');
  L.push(`Generated by solpreflight ${res.version}. Scanned ${res.filesScanned.length} Solidity file(s).`, '');
  L.push('> This is a checklist aid for self-review before an audit. It is not an audit and gives no security guarantee. Hits are pattern matches that need human review; many will be false positives, and many real issues will not be detected.', '');
  const counts = { high: 0, medium: 0, low: 0, info: 0 };
  for (const f of res.findings) counts[byId[f.rule].priority]++;
  L.push('## Summary', '', '| Review priority | Hits |', '|---|---|');
  for (const p of ['high', 'medium', 'low', 'info']) L.push(`| ${p} | ${counts[p]} |`);
  if (res.readiness) L.push('', `Pre-audit readiness: **${res.readiness.score}/${res.readiness.total}** items present.`);
  L.push('', '## Checklist', '');
  const cats = [...new Set(rules.map(r => r.category))];
  for (const cat of cats) {
    L.push(`### ${cat}`, '');
    const catRules = rules.filter(r => r.category === cat).sort((a, b) => PRIORITY_ORDER[a.priority] - PRIORITY_ORDER[b.priority]);
    for (const r of catRules) {
      const hits = res.findings.filter(f => f.rule === r.id);
      L.push(`- [${hits.length ? ' ' : 'x'}] **${r.id}** ${r.title} — _${r.priority} review priority_ — ${hits.length ? `${hits.length} hit(s)` : 'no hits'}`);
      if (hits.length) {
        L.push(`  - Why it matters: ${r.why}`, `  - How to verify: ${r.verify}`);
        for (const h of hits.slice(0, 25)) L.push(`  - \`${h.file}:${h.line}\` ${h.note ? '— ' + h.note.replace(/`/g, "'") : ''}`);
        if (hits.length > 25) L.push(`  - …and ${hits.length - 25} more (see --json)`);
      }
    }
    L.push('');
  }
  if (res.readiness) {
    L.push('## Pre-audit readiness', '', '| ID | Item | Status | Detail |', '|---|---|---|---|');
    for (const i of res.readiness.items) L.push(`| ${i.id} | ${i.label} | ${i.ok ? 'present' : 'missing'} | ${esc(i.detail)} |`);
    L.push('');
  }
  const h = res.handoff;
  L.push('## Auditor handoff', '', '### Contracts', '', '| Contract | Kind | File | nSLOC | Inherits |', '|---|---|---|---|---|');
  for (const c of h.contracts) L.push(`| ${c.name} | ${c.kind} | \`${c.file}:${c.line}\` | ${c.loc} | ${esc(c.inherits.join(', ')) || '-'} |`);
  L.push('', `Total nSLOC (non-blank, non-comment lines in contract bodies): ${h.contracts.reduce((a, c) => a + c.loc, 0)}`, '');
  L.push('### External state-changing entry points (no access check detected)', '');
  if (!h.entry.length) L.push('_none_');
  for (const e of h.entry) L.push(`- \`${e.contract}.${e.fn}()\`${e.payable ? ' (payable)' : ''} — \`${e.file}:${e.line}\``);
  L.push('', '### Privileged functions', '');
  if (!h.privileged.length) L.push('_none_');
  for (const e of h.privileged) L.push(`- \`${e.contract}.${e.fn}()\` [${e.modifiers.join(' ') || 'inline msg.sender check'}] — \`${e.file}:${e.line}\``);
  L.push('', '### External dependencies (imports)', '');
  if (!h.deps.length) L.push('_none_');
  for (const d of h.deps) L.push(`- ${d}`);
  L.push('', '---', 'Limitations: regex and lightweight parsing only (no compiler, no data-flow analysis). Inherited modifiers, assembly, and cross-contract flows are not understood. Treat every hit as a question, not a verdict.', '');
  return L.join('\n');
}

function toJSON(res) {
  return JSON.stringify({ ...res, rules: rules.map(({ check, ...r }) => r) }, null, 2);
}

module.exports = { toMarkdown, toJSON };
